export function generateMmdvmServiceUnit(): string {
  return `[Unit]
Description=MMDVMHost Digital Voice RF Modem Service
After=network-online.target dmrgateway.service
Wants=network-online.target dmrgateway.service

[Service]
Type=simple
User=mmdvm
Group=mmdvm
SupplementaryGroups=dialout
ExecStart=/usr/local/bin/MMDVMHost /etc/mmdvm/MMDVM.ini
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
`;
}

export function generateDmrGatewayServiceUnit(): string {
  return `[Unit]
Description=DMRGateway Digital Voice Network Bridge
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=mmdvm
Group=mmdvm
ExecStart=/usr/local/bin/DMRGateway /etc/mmdvm/DMRGateway.ini
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
`;
}

export function generateInstallScript(config: MmdvmConfiguration): string {
  const mmdvmIni = generateMmdvmIni(config);
  const dmrGwIni = generateDmrGatewayIni(config);
  const mmdvmSvc = generateMmdvmServiceUnit();
  const dmrGwSvc = generateDmrGatewayServiceUnit();
  const { modem, networks, system } = config;

  return `#!/usr/bin/env bash
# ============================================================================
# MMDVMHost & DMRGateway Automated Installer
# Generated by MMDVM WebGUI Configurator
# Targets: Raspberry Pi OS (Bookworm / Trixie) & Debian 12/13
# ============================================================================
set -euo pipefail

if [[ "\${EUID}" -ne 0 ]]; then
  echo "[ERROR] Run as root: sudo bash $0"
  exit 1
fi

export DEBIAN_FRONTEND=noninteractive

echo "=== [1/4] System Dependencies, Hostname & MMDVM System User ==="
hostnamectl set-hostname "${sanitizeIniLine(system.hostname)}" || true
timedatectl set-timezone "${sanitizeIniLine(system.timezone)}" || true

apt-get update -y
apt-get install -y --no-install-recommends \\
  git curl ca-certificates build-essential g++ make \\
  nlohmann-json3-dev libmosquitto-dev libsamplerate0-dev

if ! id -u mmdvm >/dev/null 2>&1; then
  useradd --user-group -M --system mmdvm --shell /bin/false
fi
usermod -aG dialout mmdvm || true
mkdir -p /etc/mmdvm /var/log/mmdvm

${
  modem.configurePiUart
    ? `if command -v raspi-config >/dev/null 2>&1; then
  echo "[INFO] Enabling Raspberry Pi GPIO hardware UART (disabling serial login console)..."
  raspi-config nonint do_serial_hw 0 || true
  raspi-config nonint do_serial_cons 1 || true
fi`
    : '# Pi GPIO UART auto-configuration skipped per modem selection'
}

echo "=== [2/4] Compile & Install g4klx/MMDVMHost ==="
rm -rf /usr/local/src/MMDVMHost
git clone --depth 1 https://github.com/g4klx/MMDVMHost.git /usr/local/src/MMDVMHost
make -C /usr/local/src/MMDVMHost -j"$(nproc)"
if [[ -f /usr/local/src/MMDVMHost/MMDVM-Host ]]; then
  install -m 0755 /usr/local/src/MMDVMHost/MMDVM-Host /usr/local/bin/MMDVMHost
else
  install -m 0755 /usr/local/src/MMDVMHost/MMDVMHost /usr/local/bin/MMDVMHost
fi

echo "=== [3/4] Compile & Install g4klx/DMRGateway ==="
rm -rf /usr/local/src/DMRGateway
git clone --depth 1 https://github.com/g4klx/DMRGateway.git /usr/local/src/DMRGateway
make -C /usr/local/src/DMRGateway -j"$(nproc)"
install -m 0755 /usr/local/src/DMRGateway/DMRGateway /usr/local/bin/DMRGateway

echo "=== [4/4] Write Config Files, Lookup Tables & Systemd Units ==="
curl -fsSL "https://radioid.net/static/user.csv" -o /etc/mmdvm/DMRIds.dat || touch /etc/mmdvm/DMRIds.dat
for f in NXDN.csv RSSI.dat; do
  if [[ -f "/usr/local/src/MMDVMHost/\${f}" && ! -f "/etc/mmdvm/\${f}" ]]; then
    cp "/usr/local/src/MMDVMHost/\${f}" "/etc/mmdvm/\${f}"
  elif [[ ! -f "/etc/mmdvm/\${f}" ]]; then
    touch "/etc/mmdvm/\${f}"
  fi
done

cat <<'EOF_MMDVM_INI' > /etc/mmdvm/MMDVM.ini
${mmdvmIni}EOF_MMDVM_INI

cat <<'EOF_DMRGW_INI' > /etc/mmdvm/DMRGateway.ini
${dmrGwIni}EOF_DMRGW_INI

chown -R mmdvm:mmdvm /etc/mmdvm /var/log/mmdvm
chmod 0640 /etc/mmdvm/DMRGateway.ini

cat <<'EOF_DMRGW_SVC' > /etc/systemd/system/dmrgateway.service
${dmrGwSvc}EOF_DMRGW_SVC

cat <<'EOF_MMDVM_SVC' > /etc/systemd/system/mmdvmhost.service
${mmdvmSvc}EOF_MMDVM_SVC

${
  system.enableUfw
    ? `apt-get install -y ufw
ufw default deny incoming
ufw default allow outgoing
ufw allow ${system.sshPort}/tcp comment 'SSH'
ufw allow ${system.webguiPort}/tcp comment 'MMDVM WebGUI'
ufw allow ${networks.dmrMasterPort}/udp comment 'DMR Master'
ufw --force enable`
    : '# UFW firewall configuration skipped'
}

systemctl daemon-reload
${networks.dmrEnable ? 'systemctl enable --now dmrgateway.service\nsystemctl restart dmrgateway.service' : 'systemctl disable --now dmrgateway.service 2>/dev/null || true'}
systemctl enable --now mmdvmhost.service
systemctl restart mmdvmhost.service

echo ""
echo "========================================================================"
echo " MMDVM Installation Complete!"
echo " Check status: systemctl status dmrgateway mmdvmhost"
echo "========================================================================"
`;
}

export function generateAllFiles(config: MmdvmConfiguration): GeneratedFile[] {
  return [
    {
      id: 'mmdvm-ini',
      filename: 'MMDVM.ini',
      targetPath: '/etc/mmdvm/MMDVM.ini',
      language: 'ini',
      description: 'Primary MMDVMHost RF modem, frequency, levels, and local network configuration',
      content: generateMmdvmIni(config),
    },
    {
      id: 'dmrgateway-ini',
      filename: 'DMRGateway.ini',
      targetPath: '/etc/mmdvm/DMRGateway.ini',
      language: 'ini',
      description: 'DMRGateway bridge linking local MMDVMHost (127.0.0.1) to your DMR master server',
      content: generateDmrGatewayIni(config),
    },
    {
      id: 'mmdvmhost-service',
      filename: 'mmdvmhost.service',
      targetPath: '/etc/systemd/system/mmdvmhost.service',
      language: 'systemd',
      description: 'Systemd service unit running MMDVMHost under the mmdvm user in group dialout',
      content: generateMmdvmServiceUnit(),
    },
    {
      id: 'dmrgateway-service',
      filename: 'dmrgateway.service',
      targetPath: '/etc/systemd/system/dmrgateway.service',
      language: 'systemd',
      description: 'Systemd service unit running DMRGateway under the mmdvm user',
      content: generateDmrGatewayServiceUnit(),
    },
    {
      id: 'install-mmdvm-sh',
      filename: 'install-mmdvm.sh',
      targetPath: './install-mmdvm.sh',
      language: 'bash',
      description: 'Standalone automated bash installer script for Raspberry Pi OS & Debian 12/13',
      content: generateInstallScript(config),
    },
  ];
}
