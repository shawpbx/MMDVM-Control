import { GeneratedFile, MmdvmConfiguration } from '../types/mmdvmConfig';
import { mhzToHz } from './validation';

function sanitizeIniLine(value: string): string {
  return value.replace(/[\r\n]/g, '').trim();
}

export function getFullDmrId(config: MmdvmConfiguration): string {
  const base = config.station.dmrId.trim() || '3100000';
  const suffix = config.station.essidSuffix.trim();
  return suffix ? `${base}${suffix}` : base;
}

